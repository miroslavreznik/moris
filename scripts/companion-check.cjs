const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { readFile, mkdir } = require('node:fs/promises');
const path = require('node:path');
const base = process.env.MORIS_TEST_URL || 'http://127.0.0.1:4173';
const output = path.resolve('test-results');
const nav = (page, name) => page.locator('.bottom-nav').getByRole('button', { name, exact: true }).click();
let browser;

(async () => {
  await mkdir(output, { recursive: true });
  browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: process.env.MORIS_BROWSER || 'msedge' } : {}) });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, timezoneId: 'Europe/Budapest', acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(12000);
  await page.clock.setFixedTime(new Date('2026-11-04T12:00:00+01:00'));
  await page.goto(base);
  await page.getByRole('button', { name: 'Choose your Moris', exact: true }).click();
  await page.getByRole('button', { name: 'Moris color: Lagoon', exact: true }).click();
  await page.getByRole('button', { name: 'Moris detail: Crooked antenna', exact: true }).click();
  await page.getByRole('button', { name: 'Save my Moris', exact: true }).click();
  await page.locator('.welcome-heading .moris-art[data-color="lagoon"][data-detail="antenna"]').waitFor();
  for (const name of ['Read a few pages', 'Go for a walk', 'Phone-free morning']) await page.getByRole('checkbox', { name, exact: true }).check();
  await page.getByLabel('Your own habit', { exact: true }).fill('A moment outside');
  await page.getByRole('button', { name: 'Add your own habit', exact: true }).click();
  await page.getByRole('button', { name: "Let's begin with 4", exact: true }).click();
  await page.locator('.today-moris .moris-art[data-color="lagoon"][data-detail="antenna"][data-motion="greet"]').waitFor();
  await page.getByRole('button', { name: 'Say hello to Moris', exact: true }).click();
  await page.getByText('0 XP', { exact: true }).first().waitFor();
  console.log('PASS onboarding previews color and detail choices live and preserves a chosen Moris; saying hello grants no XP');

  for (const [name, motion] of [['Read a few pages', 'hop'], ['Go for a walk', 'wiggle'], ['Phone-free morning', 'spin']]) {
    await page.getByRole('button', { name: `Complete ${name} today`, exact: true }).click();
    assert.equal(await page.locator('.today-moris .moris-art').getAttribute('data-motion'), motion);
  }
  const celebration = page.getByRole('dialog');
  await celebration.getByRole('heading', { name: 'Finny Moris', exact: true }).waitFor();
  await celebration.locator('.evolution-before .moris-art[data-stage="0"]').waitFor();
  await celebration.locator('.evolution-after .moris-art[data-stage="1"][data-color="lagoon"][data-detail="antenna"]').waitFor();
  await page.getByRole('button', { name: 'Skip animation', exact: true }).click();
  assert.equal(await celebration.locator('.evolution-before').isVisible(), false);
  await celebration.screenshot({ path: path.join(output, 'moris-first-evolution.png') });
  await page.getByRole('button', { name: 'Keep showing up', exact: true }).click();
  await page.getByRole('button', { name: 'Complete A moment outside today', exact: true }).click();
  assert.equal(await page.locator('.today-moris .moris-art').getAttribute('data-motion'), 'all-done');
  await page.getByText('40 XP', { exact: true }).first().waitFor();
  console.log('PASS three completion reactions, a skippable evolution at 3 wins, and a larger last-goal reaction retain the personal appearance');

  await nav(page, 'Moris');
  assert.equal(await page.locator('.evolution-ladder .moris-art[data-color="lagoon"][data-detail="antenna"]').count(), 7);
  await page.getByRole('button', { name: 'Make this Moris yours', exact: true }).click();
  await page.getByRole('button', { name: 'Moris color: Moss', exact: true }).click();
  await page.getByRole('button', { name: 'Moris detail: Little tuft', exact: true }).click();
  await page.setViewportSize({ width: 320, height: 800 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const overflowing = await page.getByRole('dialog').evaluate(dialog => dialog.scrollWidth > dialog.clientWidth);
  assert.equal(overflowing, false);
  await page.setViewportSize({ width: 1000, height: 1200 });
  await page.getByRole('dialog').screenshot({ path: path.join(output, 'moris-personalization.png') });
  await page.getByRole('button', { name: 'Save my Moris', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('.evolution-ladder .moris-art[data-color="moss"][data-detail="tuft"]').count(), 7);
  await nav(page, 'Today');
  await page.reload();
  await page.locator('.today-moris .moris-art[data-color="moss"][data-detail="tuft"]').waitFor();
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.getByText('40 XP', { exact: true }).first().waitFor();
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')); });
  await page.clock.setFixedTime(new Date('2026-11-04T12:02:00+01:00'));
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: false }); document.dispatchEvent(new Event('visibilitychange')); delete document.hidden; });
  await page.locator('.today-moris .moris-art[data-motion="greet"]').waitFor();
  await page.getByText('40 XP', { exact: true }).first().waitFor();
  console.log('PASS all seven forms carry the chosen color and quirk, the editor fits 320px, and reload preserves appearance and progress');

  await nav(page, 'Settings');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export backup', exact: true }).click();
  const download = await downloadEvent, backupPath = path.join(output, 'personal-moris-backup.json');
  await download.saveAs(backupPath);
  const backup = JSON.parse(await readFile(backupPath));
  assert.equal(backup.settings.morisColor, 'moss'); assert.equal(backup.settings.morisDetail, 'tuft');
  const restoredContext = await browser.newContext({ viewport: { width: 390, height: 844 }, timezoneId: 'Europe/Budapest', acceptDownloads: true });
  const restored = await restoredContext.newPage();
  await restored.goto(base); await restored.getByRole('button', { name: 'Start with a blank page', exact: true }).click();
  await nav(restored, 'Settings');
  await restored.getByLabel('Choose Moris backup file', { exact: true }).setInputFiles(backupPath);
  await restored.getByRole('button', { name: 'Back up & replace records', exact: true }).click();
  await nav(restored, 'Today');
  await restored.locator('.today-moris .moris-art[data-color="moss"][data-detail="tuft"]').waitFor();
  await restored.getByText('40 XP', { exact: true }).first().waitFor();
  console.log('PASS export and restore into another installation preserve the personal Moris, all four completions, and XP');

  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.reload();
  await context.setOffline(true);
  await page.reload();
  await page.locator('.today-moris .moris-art[data-color="moss"][data-detail="tuft"]').waitFor();
  await page.getByRole('button', { name: 'Say hello to Moris', exact: true }).click();
  await page.getByText('40 XP', { exact: true }).first().waitFor();
  await context.setOffline(false);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByRole('button', { name: 'Say hello to Moris', exact: true }).click();
  assert.equal(await page.locator('.today-moris .moris-character').evaluate(element => getComputedStyle(element).animationName), 'none');
  assert.equal(await page.locator('.today-moris .moris-eye').evaluate(element => getComputedStyle(element).animationName), 'none');
  await nav(page, 'Settings');
  await page.getByRole('checkbox', { name: /Extra animations/ }).uncheck();
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await nav(page, 'Today');
  await page.getByRole('button', { name: 'Say hello to Moris', exact: true }).click();
  assert.equal(await page.locator('.today-moris .moris-character').evaluate(element => getComputedStyle(element).animationName), 'none');
  console.log('PASS offline launch retains appearance; system reduced motion and the app preference both disable creature movement');
  assert.deepEqual(errors, []);
  await browser.close();
})().catch(async error => { console.error(error); await browser?.close(); process.exitCode = 1; });
